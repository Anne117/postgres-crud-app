def score(threat: dict) -> float:
    """Итоговый риск: сумма критериев DREAD (от 5 до 25)."""
    return float(sum(threat["dread"]))


def ranked() -> list[dict]:
    """Угрозы, отсортированные по убыванию оценки риска."""
    out = []
    for t in THREATS:
        t = dict(t)
        t["score"] = score(t)
        t["bdu"] = BDU.get(t["id"])
        out.append(t)
    out.sort(key=lambda t: (-t["score"], t["id"]))
    return out


def load_dump() -> None:
    """Печатает сводку для быстрой проверки."""
    for t in ranked():
        print(f"{t['score']:>4.0f}  {t['id']}  {t['stride']}  "
              f"{t['target']:<12} {t['title'][:70]}")


if __name__ == "__main__":
    load_dump()
